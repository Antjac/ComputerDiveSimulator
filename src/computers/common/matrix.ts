const P = 10; // pitch of a pixel in SVG units
const R = 4.2; // half the size of a lit square

/**
 * Renders `text` as a dot-matrix string. `cells`, when given, right-aligns the text in that many
 * full-width character cells (the other positions stay blank, as on the device).
 */
export function dotMatrix(text: string, cls = '', cells = 0): string {
  let chars = [...text];
  const width = (ch: string) => (GLYPHS[ch] ?? GLYPHS[' '])[0].length;
  const full = chars.reduce((a, c) => a + width(c) + 1, 0);
  if (cells > 0) {
    const want = cells * 6;
    while (chars.reduce((a, c) => a + width(c) + 1, 0) + 3 <= want) chars = [' ', ...chars];
  }
  let x = 0;
  let on = '';
  for (const ch of chars) {
    const g = GLYPHS[ch] ?? GLYPHS[' '];
    g.forEach((row, y) => {
      for (let i = 0; i < row.length; i++) if (row[i] === '#') on += `<rect x="${(x + i) * P + P / 2 - R}" y="${y * P + P / 2 - R}" width="${2 * R}" height="${2 * R}"/>`;
    });
    x += g[0].length + 1;
  }
  const w = Math.max(1, (cells > 0 ? Math.max(x, full) : x) - 1) * P;
  return `<svg class="dm ${cls}" viewBox="0 0 ${w} ${7 * P}" preserveAspectRatio="xMaxYMid meet"><g class="dm-on">${on}</g></svg>`;
}
